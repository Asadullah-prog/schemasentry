"""Command-line interface for SchemaSentry.

Exit codes: 0 = success · 1 = validation failure · 2 = operational/config error.
"""

from __future__ import annotations

import datetime as _datetime
import json
import traceback
from pathlib import Path
from typing import Any

import typer
from rich.console import Console
from rich.table import Table

from schemasentry import __version__
from schemasentry.contract import ContractError, load_contract
from schemasentry.profiler import profile as profile_dataset
from schemasentry.readers import DatasetError, read_dataset
from schemasentry.validator import ValidationReport, validate

app = typer.Typer(
    name="schemasentry",
    help="Privacy-first, local-first data contract validation for CSV, Excel, and JSON.",
    no_args_is_help=True,
)
console = Console()
err_console = Console(stderr=True)
_VERBOSE = {"on": False}


@app.callback()
def _main(
    verbose: bool = typer.Option(False, "--verbose", help="Show full tracebacks on errors."),
) -> None:
    _VERBOSE["on"] = verbose


def _fail(message: str) -> typer.Exit:
    err_console.print(f"[red]Error:[/red] {message}")
    if _VERBOSE["on"]:
        traceback.print_exc()
    raise typer.Exit(code=2)


def _load_dataset(
    dataset: str, sheet: str | None, input_format: str | None
) -> Any:  # returns Dataset
    try:
        return read_dataset(dataset, sheet=sheet, format=input_format)
    except DatasetError as exc:
        _fail(str(exc))
    raise AssertionError("unreachable")


def _load_contract(contract: str):
    try:
        return load_contract(contract)
    except ContractError as exc:
        _fail(str(exc))
    raise AssertionError("unreachable")


def _print_json(payload: Any, output: str | None) -> None:
    # Machine-readable output bypasses Rich so it is never wrapped or styled.
    text = json.dumps(payload, indent=2, sort_keys=False, default=str)
    if output:
        Path(output).write_text(text + "\n", encoding="utf-8")
        console.print(f"Wrote JSON output to [green]{output}[/green]")
    else:
        typer.echo(text)


@app.command()
def profile(
    dataset: str = typer.Argument(..., help="Path to the dataset file."),
    sheet: str | None = typer.Option(None, "--sheet", help="Excel worksheet name (.xlsx only)."),
    input_format: str | None = typer.Option(
        None, "--input-format", help="Override format detection: csv, xlsx, json, jsonl."
    ),
    format: str = typer.Option("terminal", "--format", help="Output format: terminal or json."),
    output: str | None = typer.Option(None, "--output", help="Write output to a file."),
) -> None:
    """Inspect a dataset and report observed statistics."""
    if format not in ("terminal", "json"):
        _fail(f"--format must be 'terminal' or 'json', got {format!r}.")
    data = _load_dataset(dataset, sheet, input_format)
    prof = profile_dataset(data)
    if format == "json":
        _print_json(prof, output)
        return
    if output:
        _fail("--output with terminal format is not supported; use --format json.")

    console.print(
        f"\n[bold]Profile:[/bold] {prof['dataset']} "
        f"({prof['format']}{', sheet ' + prof['sheet'] if prof['sheet'] else ''})"
    )
    console.print(
        f"Rows: [bold]{prof['row_count']}[/bold]   "
        f"Columns: [bold]{prof['column_count']}[/bold]   "
        f"Duplicate rows: [bold]{prof['duplicate_rows']}[/bold]\n"
    )
    table = Table(show_header=True, header_style="bold")
    for header in (
        "column",
        "inferred_type",
        "missing",
        "missing_%",
        "distinct",
        "min",
        "max",
        "mean",
        "median",
    ):
        table.add_column(header)
    for col in prof["columns"]:
        table.add_row(
            col["name"],
            col["inferred_type"],
            str(col["missing_count"]),
            f"{col['missing_pct']:.1f}",
            str(col["distinct_count"]),
            str(col.get("min", "—")),
            str(col.get("max", "—")),
            f"{col['mean']:.3g}" if "mean" in col else "—",
            f"{col['median']:.3g}" if "median" in col else "—",
        )
    console.print(table)
    console.print(f"[dim]{prof['note']}[/dim]\n")


def _generate_contract_text(prof: dict[str, Any], source: str) -> str:
    lines = [
        "# SchemaSentry contract — generated starter. REVIEW BEFORE USE.",
        f"# Generated from: {source}",
        "# Lines marked INFERRED are guesses from observed data, not guarantees.",
        "# Uncomment and adjust the optional rules to match your expectations.",
        'version: "1"',
        f"name: {Path(source).stem}",
        'description: "Starter contract generated by `schemasentry init`. Review and edit."',
        "",
        "# Tokens treated as missing values (in addition to empty cells).",
        'missing_values: ["NA", "N/A", "null", "NULL", "None", "none"]',
        "",
        "columns:",
    ]
    for col in prof["columns"]:
        name = col["name"]
        inferred = col["inferred_type"]
        nullable = col["missing_count"] > 0
        lines.append(f"  {name}:")
        lines.append(f"    type: {inferred}  # INFERRED from observed values")
        lines.append("    required: true")
        lines.append(
            f"    nullable: {'true' if nullable else 'false'}"
            f"  # INFERRED: {'missing values observed' if nullable else 'no missing values observed'}"
        )
        lines.append("    unique: false  # set to true after review if this column is a key")
        if inferred == "string":
            lines.append('    # regex: "^...$"  # uncomment to enforce a pattern')
            if 1 < col["distinct_count"] <= 20:
                lines.append("    # allowed_values: []  # uncomment and list permitted values")
            lines.append("    # min_length: 1  # uncomment to enforce a minimum length")
            lines.append("    # max_length: 255  # uncomment to enforce a maximum length")
        elif inferred in ("integer", "float"):
            lines.append(f"    # min: {col['min']}  # observed minimum; uncomment to enforce")
            lines.append(f"    # max: {col['max']}  # observed maximum; uncomment to enforce")
    lines += [
        "",
        "row_counts:",
        "  min_rows: 1  # the dataset must not be empty",
        "  # max_rows: 1000000  # uncomment to cap the expected row count",
        "",
        "strictness:",
        "  extra_columns: warn  # error | warn | ignore — how to treat unexpected columns",
        "",
    ]
    return "\n".join(lines)


@app.command("init")
def init_cmd(
    dataset: str = typer.Argument(..., help="Path to the dataset file."),
    output: str = typer.Option("schemasentry.yml", "--output", help="Contract file to write."),
    sheet: str | None = typer.Option(None, "--sheet", help="Excel worksheet name (.xlsx only)."),
    input_format: str | None = typer.Option(
        None, "--input-format", help="Override format detection: csv, xlsx, json, jsonl."
    ),
    force: bool = typer.Option(False, "--force", help="Overwrite an existing contract file."),
) -> None:
    """Generate a starter YAML contract from a dataset."""
    data = _load_dataset(dataset, sheet, input_format)
    out_path = Path(output)
    if out_path.exists() and not force:
        _fail(f"{output} already exists; use --force to overwrite.")
    prof = profile_dataset(data)
    text = _generate_contract_text(prof, dataset)
    try:
        out_path.write_text(text, encoding="utf-8")
    except OSError as exc:
        _fail(f"cannot write {output}: {exc.strerror or exc}")
    # Self-check: the generated contract must parse.
    try:
        load_contract(out_path)
    except ContractError as exc:  # pragma: no cover - defensive
        _fail(f"generated contract failed self-validation: {exc}")
    console.print(f"Wrote starter contract to [green]{output}[/green]")
    console.print("[yellow]Review the INFERRED rules before relying on this contract.[/yellow]")


@app.command("check")
def check_cmd(
    dataset: str = typer.Argument(..., help="Path to the dataset file."),
    contract: str = typer.Option(..., "--contract", help="Path to the YAML contract."),
    sheet: str | None = typer.Option(None, "--sheet", help="Excel worksheet name (.xlsx only)."),
    input_format: str | None = typer.Option(
        None, "--input-format", help="Override format detection: csv, xlsx, json, jsonl."
    ),
    format: str = typer.Option("terminal", "--format", help="Output format: terminal or json."),
    output: str | None = typer.Option(None, "--output", help="Write output to a file."),
) -> None:
    """Validate a dataset against a YAML contract."""
    if format not in ("terminal", "json"):
        _fail(f"--format must be 'terminal' or 'json', got {format!r}.")
    data = _load_dataset(dataset, sheet, input_format)
    rules = _load_contract(contract)
    report = validate(data, rules, contract_path=contract)
    if format == "json":
        _print_json(_report_payload(report), output)
    else:
        if output:
            _fail("--output with terminal format is not supported; use --format json.")
        _print_terminal_report(report)
    if not report.passed:
        raise typer.Exit(code=1)


@app.command("report")
def report_cmd(
    dataset: str = typer.Argument(..., help="Path to the dataset file."),
    contract: str = typer.Option(..., "--contract", help="Path to the YAML contract."),
    sheet: str | None = typer.Option(None, "--sheet", help="Excel worksheet name (.xlsx only)."),
    input_format: str | None = typer.Option(
        None, "--input-format", help="Override format detection: csv, xlsx, json, jsonl."
    ),
    format: str = typer.Option("terminal", "--format", help="Output format: terminal or json."),
    output: str | None = typer.Option(None, "--output", help="Write the report to a file."),
) -> None:
    """Produce a structured validation report (passed/failed checks, violations,
    column summaries) without leaking sample values."""
    if format not in ("terminal", "json"):
        _fail(f"--format must be 'terminal' or 'json', got {format!r}.")
    data = _load_dataset(dataset, sheet, input_format)
    rules = _load_contract(contract)
    report = validate(data, rules, contract_path=contract)
    payload = _report_payload(report)
    if format == "json":
        _print_json(payload, output)
    else:
        if output:
            Path(output).write_text(_render_terminal_report_text(report) + "\n", encoding="utf-8")
            console.print(f"Wrote terminal report to [green]{output}[/green]")
        else:
            _print_terminal_report(report, detailed=True)
    if not report.passed:
        raise typer.Exit(code=1)


def _report_payload(report: ValidationReport) -> dict[str, Any]:
    payload = report.to_dict()
    payload["tool"] = f"schemasentry {__version__}"
    payload["generated_at"] = _datetime.datetime.now(_datetime.UTC).isoformat(timespec="seconds")
    return payload


def _print_terminal_report(report: ValidationReport, detailed: bool = False) -> None:
    console.print(_render_terminal_report_text(report, detailed=detailed))


def _render_terminal_report_text(report: ValidationReport, detailed: bool = False) -> str:
    # Render via Rich to a string so it can also be written to a file.
    import io

    from rich.console import Console as _C

    buf = _C(record=True, width=100, file=io.StringIO())
    status = "[green]PASSED[/green]" if report.passed else "[red]FAILED[/red]"
    buf.print(f"\n[bold]Validation {status}[/bold] — {report.dataset}")
    buf.print(f"Contract: {report.contract}")
    buf.print(
        f"Rows: {report.row_count}   Checks passed: [green]{report.checks_passed}[/green]   "
        f"Checks failed: [red]{report.checks_failed}[/red]"
    )
    errors = report.errors
    warnings = report.warnings
    if errors:
        table = Table(title="Violations", show_header=True, header_style="bold")
        table.add_column("rule")
        table.add_column("column")
        table.add_column("count")
        table.add_column("example rows")
        table.add_column("message")
        for v in errors:
            table.add_row(
                v.rule,
                v.column or "—",
                str(v.count),
                ",".join(map(str, v.example_rows)) or "—",
                v.message,
            )
        buf.print(table)
    if warnings:
        buf.print("[yellow]Warnings:[/yellow]")
        for v in warnings:
            buf.print(f"  [yellow]•[/yellow] {v.message}")
    if detailed and report.column_summaries:
        table = Table(title="Column summaries", show_header=True, header_style="bold")
        table.add_column("column")
        table.add_column("rules checked")
        table.add_column("rules failed")
        table.add_column("violations")
        for name, summary in report.column_summaries.items():
            table.add_row(
                name,
                str(summary["rules_checked"]),
                ", ".join(summary["rules_failed"]) or "—",
                str(summary["violation_count"]),
            )
        buf.print(table)
    if report.passed:
        buf.print("[green]All checks passed.[/green]\n")
    return buf.export_text()


def main() -> None:
    app()


if __name__ == "__main__":
    main()
